// clangd Rerank — routes clangd through resources/clangd_rerank_proxy.py by pointing clangd.path at a
// generated launcher script. The proxy is plain Python (stdlib only); the third-stage model is either a
// local Kev server, the Jev hosted API, or nothing (stage 2 only).
import * as vscode from 'vscode';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { spawnSync } from 'child_process';

const SECTION = 'clangdRerank';
const SECRET_KEY = 'clangdRerank.jevApiKey';
const STATE_ORIGINAL_PATH = 'clangdRerank.originalClangdPath';
const LAUNCHER_NAME = 'clangd-rerank-launch.sh';

let status: vscode.StatusBarItem;
let output: vscode.OutputChannel;

function cfg() {
  return vscode.workspace.getConfiguration(SECTION);
}

function launcherPath(ctx: vscode.ExtensionContext) {
  return path.join(ctx.globalStorageUri.fsPath, LAUNCHER_NAME);
}

function logPath(ctx: vscode.ExtensionContext) {
  return path.join(ctx.globalStorageUri.fsPath, 'proxy.log');
}

/** Usage measurements (RERANK_STATS): one JSON line per completion site = the identifier the user ended up
 *  writing and its rank in clangd's / stage-2 / final order. Never contains code text. */
function statsPath(ctx: vscode.ExtensionContext) {
  return path.join(ctx.globalStorageUri.fsPath, 'rerank-stats.jsonl');
}

function shq(s: string) {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** The clangd binary the proxy should launch: whatever clangd.path was before we took it over, else the setting. */
function realClangd(ctx: vscode.ExtensionContext) {
  const original = ctx.globalState.get<string | null>(STATE_ORIGINAL_PATH, null);
  if (original && !original.endsWith(LAUNCHER_NAME)) {
    return original;
  }
  return cfg().get<string>('clangdPath', 'clangd');
}

async function writeLauncher(ctx: vscode.ExtensionContext): Promise<string> {
  const c = cfg();
  const backend = c.get<string>('backend', 'local');
  const python = c.get<string>('pythonPath', 'python3');
  const stage2 = c.get<string>('stage2ModelPath', '') || path.join(ctx.extensionPath, 'resources', 'stage2_v2_lgb.txt');
  const proxy = path.join(ctx.extensionPath, 'resources', 'clangd_rerank_proxy.py');
  const env: Record<string, string> = {
    CLANGD_BIN: realClangd(ctx),
    STAGE2_MODEL: stage2,
    RERANK_MAX_CANDS: String(c.get<number>('maxCandidates', 60)),
    RERANK_CTX_LINES: String(c.get<number>('contextLines', 40)),
    RERANK_TIMEOUT: (c.get<number>('timeoutMs', 400) / 1000).toString(),
    RERANK_SKIP3_TYPED: '0',
    RERANK_LOG: logPath(ctx),
  };
  if (c.get<boolean>('recordStats', false)) {
    env.RERANK_STATS = statsPath(ctx);
  }
  if (backend === 'local') {
    env.RERANK_BASE_URL = c.get<string>('localServerUrl', 'http://127.0.0.1:8009');
    env.RERANK_MODEL = 'kev-latest';
    env.TYPESAFE_API_KEY = 'local';
  } else if (backend === 'jev') {
    const key = await ctx.secrets.get(SECRET_KEY);
    if (!key) {
      vscode.window.showWarningMessage('clangd Rerank: no Jev API key stored. Run "clangd Rerank: Set Jev API key". Using stage 2 only until then.');
      env.RERANK_STAGE3 = '0';
    } else {
      env.RERANK_BASE_URL = 'https://api.typesafe.ai';
      env.RERANK_MODEL = 'jev-latest';
      env.TYPESAFE_API_KEY = key;
    }
  } else {
    env.RERANK_STAGE3 = '0';
  }
  const lines = ['#!/usr/bin/env bash', '# generated by the clangd Rerank extension; edits are overwritten'];
  for (const [k, v] of Object.entries(env)) {
    lines.push(`export ${k}=${shq(v)}`);
  }
  lines.push(`exec ${shq(python)} -I ${shq(proxy)} "$@"`, '');
  await fs.promises.mkdir(ctx.globalStorageUri.fsPath, { recursive: true, mode: 0o700 });
  const file = launcherPath(ctx);
  await fs.promises.writeFile(file, lines.join('\n'), { mode: 0o700 });
  await fs.promises.chmod(file, 0o700);
  return file;
}

function checkPython(python: string): string | undefined {
  const r = spawnSync(python, ['-c', 'import sys; print(sys.version_info[:2])'], { encoding: 'utf8' });
  if (r.error || r.status !== 0) {
    return `clangd Rerank: cannot run "${python}" (${r.error?.message ?? r.stderr}). Set clangdRerank.pythonPath.`;
  }
  return undefined;
}

async function applySuggestSelection() {
  if (!cfg().get<boolean>('setSuggestSelectionFirst', true)) {
    return;
  }
  for (const languageId of ['c', 'cpp', 'cuda-cpp', 'objective-c', 'objective-cpp']) {
    const editor = vscode.workspace.getConfiguration('editor', { languageId });
    const current = editor.inspect<string>('suggestSelection');
    if (current?.globalLanguageValue !== 'first') {
      await editor.update('suggestSelection', 'first', vscode.ConfigurationTarget.Global, true);
    }
  }
}

async function enable(ctx: vscode.ExtensionContext, restart = true) {
  const warn = checkPython(cfg().get<string>('pythonPath', 'python3'));
  if (warn) {
    vscode.window.showErrorMessage(warn);
    updateStatus('error');
    return;
  }
  const clangdCfg = vscode.workspace.getConfiguration('clangd');
  const inspected = clangdCfg.inspect<string>('path');
  const current = inspected?.globalValue ?? inspected?.workspaceValue ?? inspected?.workspaceFolderValue;
  if (current && !current.endsWith(LAUNCHER_NAME)) {
    await ctx.globalState.update(STATE_ORIGINAL_PATH, current);
  } else if (!current) {
    await ctx.globalState.update(STATE_ORIGINAL_PATH, null);
  }
  const launcher = await writeLauncher(ctx);
  if (current !== launcher) {
    await clangdCfg.update('path', launcher, vscode.ConfigurationTarget.Global);
  }
  await applySuggestSelection();
  updateStatus('on');
  if (restart) {
    await restartClangd();
  }
  output.appendLine(`[${new Date().toISOString()}] enabled: backend=${cfg().get('backend')} launcher=${launcher} clangd=${realClangd(ctx)}`);
}

async function disable(ctx: vscode.ExtensionContext) {
  const clangdCfg = vscode.workspace.getConfiguration('clangd');
  const original = ctx.globalState.get<string | null>(STATE_ORIGINAL_PATH, null);
  const inspected = clangdCfg.inspect<string>('path');
  if (inspected?.globalValue?.endsWith(LAUNCHER_NAME)) {
    await clangdCfg.update('path', original ?? undefined, vscode.ConfigurationTarget.Global);
  }
  updateStatus('off');
  await restartClangd();
  output.appendLine(`[${new Date().toISOString()}] disabled: clangd.path restored to ${original ?? '(default)'}`);
}

async function restartClangd() {
  try {
    await vscode.commands.executeCommand('clangd.restart');
  } catch (e) {
    output.appendLine(`clangd.restart failed: ${e}`);
  }
}

function updateStatus(state: 'on' | 'off' | 'error') {
  const backend = cfg().get<string>('backend', 'local');
  const label = backend === 'local' ? 'local' : backend === 'jev' ? 'Jev' : 'stage 2';
  status.text = state === 'on' ? `$(list-ordered) Rerank: ${label}` : state === 'off' ? '$(list-ordered) Rerank: off' : '$(warning) Rerank';
  status.tooltip = state === 'on'
    ? `clangd completions are reranked (${label}). Click to toggle.`
    : state === 'off' ? 'clangd Rerank is off. Click to enable.' : 'clangd Rerank could not start. See the output channel.';
  status.show();
}

export async function activate(ctx: vscode.ExtensionContext) {
  output = vscode.window.createOutputChannel('clangd Rerank');
  status = vscode.window.createStatusBarItem(vscode.StatusBarAlignment.Right, 90);
  status.command = 'clangdRerank.toggle';
  ctx.subscriptions.push(output, status);

  ctx.subscriptions.push(
    vscode.commands.registerCommand('clangdRerank.enable', async () => {
      await cfg().update('enabled', true, vscode.ConfigurationTarget.Global);
      await enable(ctx);
    }),
    vscode.commands.registerCommand('clangdRerank.disable', async () => {
      await cfg().update('enabled', false, vscode.ConfigurationTarget.Global);
      await disable(ctx);
    }),
    vscode.commands.registerCommand('clangdRerank.toggle', async () => {
      const on = cfg().get<boolean>('enabled', true);
      await cfg().update('enabled', !on, vscode.ConfigurationTarget.Global);
      await (on ? disable(ctx) : enable(ctx));
    }),
    vscode.commands.registerCommand('clangdRerank.setJevApiKey', async () => {
      const key = await vscode.window.showInputBox({
        prompt: 'TypeSafe (Jev) API key. Stored in VS Code secret storage; written only into the launcher script in extension storage (mode 0700).',
        password: true,
        ignoreFocusOut: true,
      });
      if (key) {
        await ctx.secrets.store(SECRET_KEY, key.trim());
        if (cfg().get<boolean>('enabled', true)) {
          await enable(ctx);
        }
      }
    }),
    vscode.commands.registerCommand('clangdRerank.clearJevApiKey', async () => {
      await ctx.secrets.delete(SECRET_KEY);
      if (cfg().get<boolean>('enabled', true)) {
        await enable(ctx);
      }
    }),
    vscode.commands.registerCommand('clangdRerank.showLog', async () => {
      const file = logPath(ctx);
      if (fs.existsSync(file)) {
        await vscode.window.showTextDocument(vscode.Uri.file(file), { preview: false });
      } else {
        vscode.window.showInformationMessage('clangd Rerank: no proxy log yet (trigger a completion first).');
      }
    }),
    vscode.commands.registerCommand('clangdRerank.showStats', async () => {
      const file = statsPath(ctx);
      if (!fs.existsSync(file)) {
        vscode.window.showInformationMessage('clangd Rerank: no usage statistics yet. Enable clangdRerank.recordStats and use completion for a while.');
        return;
      }
      const python = cfg().get<string>('pythonPath', 'python3');
      const script = path.join(ctx.extensionPath, 'resources', 'rerank_stats.py');
      const r = spawnSync(python, ['-I', script, file], { encoding: 'utf8' });
      output.appendLine(`--- usage statistics (${file}) ---`);
      output.appendLine(r.status === 0 ? r.stdout : `rerank_stats.py failed: ${r.stderr}`);
      output.show(true);
    }),
    vscode.commands.registerCommand('clangdRerank.restart', () => enable(ctx)),
    vscode.workspace.onDidChangeConfiguration(async (e) => {
      if (e.affectsConfiguration(SECTION)) {
        if (cfg().get<boolean>('enabled', true)) {
          await enable(ctx);
        } else {
          await disable(ctx);
        }
      }
    }),
  );

  if (os.platform() === 'win32') {
    vscode.window.showWarningMessage('clangd Rerank: Windows is not supported yet (the launcher is a bash script). Use it in WSL or on a Linux/macOS remote.');
    updateStatus('error');
    return;
  }
  if (cfg().get<boolean>('enabled', true)) {
    await enable(ctx, false); // clangd is starting anyway; restarting here would race its first launch
    const clangdCfg = vscode.workspace.getConfiguration('clangd').get<string>('path', '');
    if (clangdCfg && !clangdCfg.endsWith(LAUNCHER_NAME)) {
      await restartClangd();
    }
  } else {
    updateStatus('off');
  }
}

export async function deactivate() {
  // Leave clangd.path as is: the launcher keeps working without the extension host, and uninstall is the
  // one case we cannot hook. The README tells users to run "clangd Rerank: Disable" before uninstalling.
}
